"""Rebuild all numerical exhibits from the supplied, immutable DWRAP workbook.

No prose generation, legal inference, network calls, or UI code runs here.
Run with --check to compare generated bytes against the committed output.
"""
from pathlib import Path
from collections import Counter, defaultdict
from itertools import combinations
import argparse, csv, hashlib, io, json, math
import openpyxl

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / 'data/raw/dwrap_index.xlsx'
FIELDS = ['access', 'services', 'livelihoods', 'movement', 'participation']
LABELS = ['Access to protection', 'Services', 'Livelihoods', 'Movement', 'Citizenship & participation']
RAW_FIELDS = ['move', 'move_cond', 'camp', 'docs', 'docs_fee', 'elem_educ', 'high_educ', 'health', 'aid']
EPS = 1e-8
TOLERANCE = .005
YEAR = 2022

def serialize(obj):
    return (json.dumps(obj, ensure_ascii=False, separators=(',', ':'), allow_nan=False) + '\n').encode()

def build():
    wb = openpyxl.load_workbook(RAW, read_only=True, data_only=True)
    sheet = wb.active
    values = sheet.iter_rows(values_only=True)
    columns = next(values)
    rows = [dict(zip(columns, row)) for row in values]
    assert len(columns) == len(set(columns)) == 102
    assert len(rows) == 11628, 'Unexpected source version; review before updating expectations.'
    assert len({(r['ccode'], r['year']) for r in rows}) == len(rows), 'Duplicate country-year'
    clean = [r for r in rows if r['ccode'] not in (998,999)]
    assert len(clean) == 11484
    assert all(r['country'] and r['policy'] is not None for r in clean)
    numeric = ['dwrap_icw'] + [f + '_icw' for f in FIELDS]
    assert all(isinstance(r[k], (float,int)) and math.isfinite(r[k]) and -EPS <= r[k] <= 1+EPS for r in clean for k in numeric)
    current = sorted([r for r in clean if r['year'] == YEAR], key=lambda r:r['country'])
    assert len(current) == 198
    def scores(r):
        return {f:r[f+'_icw'] for f in FIELDS}
    records = [{ 'id':r['ccode'], 'country':r['country'], 'year':r['year'], 'total':r['dwrap_icw'], 'scores':scores(r), 'policy':r['policy'], 'codes':{k:r[k] for k in RAW_FIELDS}} for r in current]
    pairs = []
    for a,b in combinations(current, 2):
        total_gap = abs(a['dwrap_icw']-b['dwrap_icw'])
        if total_gap <= TOLERANCE:
            gaps = {f:abs(a[f+'_icw']-b[f+'_icw']) for f in FIELDS}
            largest = max(FIELDS,key=lambda f:gaps[f])
            pairs.append({'a':a['ccode'],'b':b['ccode'],'totalGap':total_gap,'gaps':gaps,'largestField':largest,'largestGap':gaps[largest]})
    pairs.sort(key=lambda p:(-p['largestGap'],p['totalGap'],p['a'],p['b']))
    for i,p in enumerate(pairs): p['rank'] = i+1
    histories = defaultdict(list)
    for r in sorted(clean,key=lambda r:(r['ccode'],r['year'])):
        histories[r['ccode']].append({'year':r['year'],'total':r['dwrap_icw'], **scores(r)})
    changed = mixed = 0
    transitions = []
    for cid,history in histories.items():
        for prev,now in zip(history,history[1:]):
            if now['year'] != prev['year']+1: continue
            delta = {f:now[f]-prev[f] for f in FIELDS}
            if any(abs(v)>EPS for v in delta.values()): changed += 1
            if any(v>EPS for v in delta.values()) and any(v < -EPS for v in delta.values()):
                mixed += 1
                transitions.append({'id':cid,'year':now['year'],'delta':delta,'totalDelta':now['total']-prev['total']})
    assert changed == 848 and mixed == 197
    curated = []
    for name,a_name,b_name in [('movement','Finland','Namibia'),('coverage','Austria','Philippines')]:
        a,b = (next(r for r in current if r['country']==n) for n in (a_name,b_name))
        pair = next(p for p in pairs if {p['a'],p['b']}=={a['ccode'],b['ccode']})
        curated.append({'key':name, 'a':a['ccode'],'b':b['ccode'],**{k:v for k,v in pair.items() if k not in ('a','b')}})
    summary = {'sourceFile':'dwrap_index.xlsx','sourceSha256':hashlib.sha256(RAW.read_bytes()).hexdigest(), 'sourceSheet':sheet.title,'sourceColumns':len(columns),'rawRows':len(rows),'excludedBenchmarkRows':len(rows)-len(clean),'countryYearRows':len(clean),'historicalEntities':len(histories),'currentEntities':len(current),'firstYear':min(r['year'] for r in clean),'lastYear':YEAR,'pairTolerance':TOLERANCE,'qualifyingPairs':len(pairs),'possiblePairs':len(current)*(len(current)-1)//2,'changedTransitions':changed,'mixedTransitions':mixed,'epsilon':EPS,'aggregation':'Supplied inverse-covariance-weighted (ICW) indices; not recomputed','excludedCodes':[998,999], 'rounding':'All calculations use workbook floating-point values. UI rounds at display time only.'}
    payload = {'summary':summary, 'fields':[{'key':f,'label':label} for f,label in zip(FIELDS,LABELS)],'countries':records,'pairs':pairs,'curated':curated}
    # CSV export retains full float representations and identifies every source cell by key.
    out = io.StringIO(newline=''); writer = csv.writer(out,lineterminator='\n')
    writer.writerow(['ccode','country','year','dwrap_icw']+[f+'_icw' for f in FIELDS]+RAW_FIELDS+['policy'])
    for r in current: writer.writerow([r[k] for k in ['ccode','country','year','dwrap_icw']+[f+'_icw' for f in FIELDS]+RAW_FIELDS+['policy']])
    return {'comparison.json':serialize(payload),'history.json':serialize(histories),'audit.json':serialize(summary),'mixed-transitions.json':serialize(transitions),'country-scores-2022.csv':out.getvalue().encode()}

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    result=build()
    for name,content in result.items():
        target=ROOT/'dist/data'/name
        if args.check:
            assert target.exists() and target.read_bytes()==content, f'Stale generated file: {name}'
        else:
            target.parent.mkdir(parents=True,exist_ok=True); target.write_bytes(content)
    print(json.dumps(json.loads(result['audit.json']),indent=2))
    print('PASS: committed exhibits match workbook.' if args.check else 'Generated numerical exhibits.')
